const lastPicked = new Map<EncouragementMoment, number>()

export function encouragement(moment: EncouragementMoment) {
  const messages = encouragements[moment]
  let index = Math.floor(Math.random() * messages.length)
  if (messages.length > 1 && index === lastPicked.get(moment)) index = (index + 1) % messages.length
  lastPicked.set(moment, index)
  return messages[index]
}

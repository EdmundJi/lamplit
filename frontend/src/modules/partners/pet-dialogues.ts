let lastDialogueIndex = -1

export function randomPetDialogue() {
  let index = Math.floor(Math.random() * PET_DIALOGUES.length)
  if (PET_DIALOGUES.length > 1 && index === lastDialogueIndex) {
    index = (index + 1) % PET_DIALOGUES.length
  }
  lastDialogueIndex = index
  return PET_DIALOGUES[index]
}
